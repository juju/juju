type templatesSuite struct {
	coretesting.BaseSuite
	root string
}

func TestTemplatesSuite(t *testing.T) {
	tc.Run(t, &templatesSuite{})
}

func (s *templatesSuite) SetUpTest(c *tc.C) {
	s.BaseSuite.SetUpTest(c)
	s.root = c.MkDir()
	c.Assert(os.MkdirAll(filepath.Join(s.root, "generate"), 0o755), tc.ErrorIsNil)
	c.Assert(os.WriteFile(filepath.Join(s.root, "go.mod"), []byte("module test\n"), 0o644), tc.ErrorIsNil)
}

// writeTemplate writes a SQL-bearing template under generate/.
func (s *templatesSuite) writeTemplate(c *tc.C, name, body string) string {
	path := filepath.Join(s.root, "generate", name)
	c.Assert(os.MkdirAll(filepath.Dir(path), 0o755), tc.ErrorIsNil)
	c.Assert(os.WriteFile(path, []byte(body), 0o644), tc.ErrorIsNil)
	return path
}

// writeGenerated writes a committed generated Go file at the repository
// relative path rel.
func (s *templatesSuite) writeGenerated(c *tc.C, rel, body string) {
	path := filepath.Join(s.root, filepath.FromSlash(rel))
	c.Assert(os.MkdirAll(filepath.Dir(path), 0o755), tc.ErrorIsNil)
	c.Assert(os.WriteFile(path, []byte("// Code generated by test. DO NOT EDIT.\n\n"+body), 0o644), tc.ErrorIsNil)
}

func (s *templatesSuite) TestNoGeneratedOutput(c *tc.C) {
	s.writeTemplate(c, "schema.tmpl", "SELECT id, name FROM {{.Table}} WHERE x = 1\n")
	notes := checkTemplates(s.root)
	c.Check(notes, tc.HasLen, 1)
	c.Check(notes[0].Path, tc.Equals, "generate/schema.tmpl")
}

func (s *templatesSuite) TestCommittedOutputNoNote(c *tc.C) {
	s.writeTemplate(c, "schema.tmpl", "SELECT id, name FROM {{.Table}} WHERE x = 1\n")
	s.writeGenerated(c, "state/schema.go", "const q = `SELECT id, name FROM users WHERE x = 1`\n")
	notes := checkTemplates(s.root)
	c.Check(notes, tc.HasLen, 0)
}

func (s *templatesSuite) TestNonSQLTemplateNoNote(c *tc.C) {
	s.writeTemplate(c, "readme.tmpl", "# {{.Title}}\nSome prose without any SQL.\n")
	notes := checkTemplates(s.root)
	c.Check(notes, tc.HasLen, 0)
}

func (s *templatesSuite) TestShortFragmentsSkipped(c *tc.C) {
	// The only SQL line has too little static text to be distinctive,
	// so no patterns are built and the line cannot match anything.
	tmpl := "SELECT {{.A}}{{.B}}{{.C}}\n"
	pats := templateSQLPatterns([]byte(tmpl))
	c.Check(pats, tc.HasLen, 0)
}

func (s *templatesSuite) TestWildcardMatches(c *tc.C) {
	tmpl := "SELECT id, name FROM {{.Table}} WHERE x = 1\n"
	pats := templateSQLPatterns([]byte(tmpl))
	c.Check(pats, tc.HasLen, 1)
	c.Check(pats[0].Match([]byte("SELECT id, name FROM users WHERE x = 1")), tc.IsTrue)
}

func (s *templatesSuite) TestBoundedGapNoMatch(c *tc.C) {
	// Two template variables with more than 160 bytes of generated
	// content between them exceed the bounded wildcard and do not
	// match. This documents the current behaviour.
	tmpl := "SELECT {{.Cols}} FROM {{.Table}} WHERE x = 1\n"
	pats := templateSQLPatterns([]byte(tmpl))
	c.Check(pats, tc.HasLen, 1)
	long := "SELECT " + strings.Repeat("col, ", 40) + "FROM users WHERE x = 1"
	c.Check(len(long) > 160+16, tc.IsTrue)
	c.Check(pats[0].Match([]byte(long)), tc.IsFalse)
}

func (s *templatesSuite) TestShouldCheckTemplates(c *tc.C) {
	domainDir := filepath.Join(s.root, "domain", "cloud", "state")
	c.Assert(os.MkdirAll(domainDir, 0o755), tc.ErrorIsNil)
	domainFile := filepath.Join(domainDir, "state.go")
	c.Assert(os.WriteFile(domainFile, []byte("package state\n"), 0o644), tc.ErrorIsNil)
	genDir := filepath.Join(s.root, "generate")
	genFile := filepath.Join(genDir, "schema.go")
	c.Assert(os.WriteFile(genFile, []byte("package generate\n"), 0o644), tc.ErrorIsNil)

	tests := []struct {
		about string
		args  []string
		want  bool
	}{{
		about: "no args covers the repository",
		args:  nil,
		want:  true,
	}, {
		about: "domain directory excludes generate",
		args:  []string{domainDir},
		want:  false,
	}, {
		about: "domain file excludes generate",
		args:  []string{domainFile},
		want:  false,
	}, {
		about: "generate directory",
		args:  []string{genDir},
		want:  true,
	}, {
		about: "file under generate",
		args:  []string{genFile},
		want:  true,
	}, {
		about: "repository root contains generate",
		args:  []string{s.root},
		want:  true,
	}, {
		about: "glob may match generated output",
		args:  []string{"domain/*/state/**"},
		want:  true,
	}, {
		about: "unreadable path stays conservative",
		args:  []string{filepath.Join(s.root, "missing")},
		want:  true,
	}}
	for _, test := range tests {
		c.Logf("test %q args %v", test.about, test.args)
		c.Check(shouldCheckTemplates(s.root, test.args), tc.Equals, test.want)
	}
}

func (s *templatesSuite) TestShouldCheckTemplatesRelativeArgs(c *tc.C) {
	// Relative arguments are resolved against the working directory,
	// as discovery does.
	cwd := c.MkDir()
	wd, err := os.Getwd()
	c.Assert(err, tc.ErrorIsNil)
	c.Assert(os.Chdir(cwd), tc.ErrorIsNil)
	defer func() {
		c.Assert(os.Chdir(wd), tc.ErrorIsNil)
	}()
	// The relative name resolves against the working directory, so it
	// points at a directory outside the repository under test.
	c.Assert(os.MkdirAll(filepath.Join(cwd, "generate"), 0o755), tc.ErrorIsNil)
	c.Assert(os.WriteFile(filepath.Join(cwd, "generate", "schema.go"),
		[]byte("package generate\n"), 0o644), tc.ErrorIsNil)
	c.Check(shouldCheckTemplates(s.root, []string{"generate/schema.go"}), tc.IsFalse)
}
